// The finder's sample catalogue (criteria 16, 18): validate the raw courses in
// src/features/finder/data/raw, build their Course rows and extras by rule, embed each course's
// name and description, drop near-duplicates, and write src/features/finder/data/catalogue.ts.
//   GOOGLE_CLOUD_PROJECT=… GOOGLE_CLOUD_LOCATION=global bun run finder:build && bun run format
//   bun run finder:build --rules-only && bun run format
// re-runs only the rules over the courses catalogue.ts already keeps, in its order: no embedding
// and no dedupe, so a change to the occupations or the rules refreshes the lines without moving
// a near-duplicate decision.
// Guard first, when it embeds: the real embedding model, since a fake vector cannot tell two
// courses apart by meaning.

import { readdir } from 'node:fs/promises'
import { join } from 'node:path'

const { aiConfig } = await import('../src/features/content/ai/config')

function fail(message: string): never {
  console.error(message)
  process.exit(1)
}

const rulesOnly = process.argv.includes('--rules-only')
const config = aiConfig(process.env)
if (!rulesOnly) {
  if (config.provider === 'fake') fail('AI_PROVIDER is fake: the build embeds with the real model.')
  if (!config.project) fail('GOOGLE_CLOUD_PROJECT is not set.')
}

const { rawCourseSchema } = await import('../src/features/finder/data/schema')
const { buildCatalogue } = await import('../src/features/finder/model/build')
const { dropNearDuplicates } = await import('../src/features/finder/model/dedupe')
const { embedAll, embedModelName } = await import('../src/features/finder/server/embed')

type RawCourse = import('../src/features/finder/data/schema').RawCourse

const DATA = join(import.meta.dir, '../src/features/finder/data')
const OUT = join(DATA, 'catalogue.ts')
const THRESHOLD = 0.95
/** Further attempts per text when the model says too many requests (429): eight in all. */
const RETRIES = 7

// 1. Read and validate.
const files = (await readdir(join(DATA, 'raw'))).filter((f) => f.endsWith('.json')).sort()
const valid: RawCourse[] = []
let rawCount = 0
let invalid = 0
for (const file of files) {
  const rows: unknown = await Bun.file(join(DATA, 'raw', file)).json()
  if (!Array.isArray(rows)) fail(`${file} is not an array of courses.`)
  rows.forEach((row, i) => {
    rawCount++
    const parsed = rawCourseSchema.safeParse(row)
    if (parsed.success) {
      valid.push(parsed.data)
      return
    }
    invalid++
    const name = (row as { name?: unknown })?.name
    const issues = parsed.error.issues.map((x) => `${x.path.join('.')}: ${x.message}`).join('; ')
    console.log(`invalid · ${file}[${i}] ${typeof name === 'string' ? name : ''} · ${issues}`)
  })
}

// 2. Build.
const { courses, extras } = buildCatalogue(valid)

// 3–4. Keep: the ids catalogue.ts already keeps (--rules-only), else embed and drop near-duplicates.
const { kept, dropped } = rulesOnly ? await keptBefore() : await dedupe()

async function keptBefore(): Promise<{ kept: string[]; dropped: [] }> {
  const { FINDER_COURSES } = await import('../src/features/finder/data/catalogue')
  const built = new Set(courses.map((c) => c.id))
  const kept = FINDER_COURSES.map((c) => c.id)
  const gone = kept.filter((id) => !built.has(id))
  if (gone.length)
    fail(`The raw files no longer give ${gone.length} kept course(s): ${gone.join(', ')}`)
  return { kept, dropped: [] }
}

async function dedupe() {
  // Embed, one text per call, backing off on 429.
  console.log(`embedding ${courses.length} courses with ${embedModelName()}`)
  const texts = courses.map((c, i) => `${c.name}. ${extras[i].description}`)
  const vectors = await embedAll(texts, 'RETRIEVAL_DOCUMENT', {
    retries: RETRIES,
    onProgress: (done, total) => {
      if (done % 50 === 0) console.log(`embedded ${done}/${total}`)
    },
  })
  const result = dropNearDuplicates(
    courses.map((c) => c.id),
    vectors,
    THRESHOLD,
  )
  for (const d of result.dropped)
    console.log(`near-duplicate · ${d.id} ~ ${d.keptId} (${d.similarity.toFixed(3)})`)
  return result
}

/** The kept rows, in the order of `kept`. */
const inOrder = <T>(rows: T[], id: (row: T) => string): T[] => {
  const byId = new Map(rows.map((r) => [id(r), r]))
  return kept.map((k) => byId.get(k) as T)
}

// 5. Write the catalogue; `bun run format` runs after. Biome skips the file: biome.json excludes it,
// since it is generated here and is over Biome's 1 MiB limit.
const date = new Date().toISOString().slice(0, 10)
const source = `// Generated by scripts/finder-build.ts from data/raw on ${date}; do not edit.
import type { Course } from '@/features/engine/types'
import type { FinderExtra } from '../model/types'

export const FINDER_COURSES: readonly Course[] = ${JSON.stringify(
  inOrder(courses, (c) => c.id),
  null,
  2,
)}

export const FINDER_EXTRAS: readonly FinderExtra[] = ${JSON.stringify(
  inOrder(extras, (e) => e.courseId),
  null,
  2,
)}
`
await Bun.write(OUT, source)

// 6. Report.
console.log(
  `raw ${rawCount} · invalid ${invalid} · near-duplicates dropped ${dropped.length} · kept ${kept.length}`,
)
