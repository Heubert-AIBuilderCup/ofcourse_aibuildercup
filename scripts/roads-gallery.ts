// The road gallery: every pick in ALL_PICKS composed by composeRoad and written to
// docs/student-ai-roads/road-gallery.md for a human read. Pure: no database, no model call.
//   bun run roads:gallery

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { cityById } from '../src/features/engine/catalogue'
import { ALL_PICKS, pickId, ROAD_CANDIDATES } from '../src/features/roads/data/candidates'
import { courseById } from '../src/features/roads/data/courses'
import { ROAD_KEYS } from '../src/features/roads/data/road-keys'
import type { RoadSpec, SlotCopy, SlotId } from '../src/features/roads/data/types'
import { composeRoad } from '../src/features/roads/model/compose'

const PR_STEPS: SlotId[] = ['fork', 'pr-straight', 'pr-point', 'pr-lane', 'pr-lane-end']
const candidateIds = new Set(ROAD_CANDIDATES.map((k) => k.id))
const writtenIds = new Set(ROAD_KEYS.map((k) => k.id))

const courseName = (id: string) => courseById(id)?.name ?? id

function stepLine(slot: string, copy: SlotCopy): string {
  const parts = [`**${slot}** — ${copy.name}`]
  if (copy.sub) parts.push(copy.sub)
  if (copy.gains) parts.push(copy.gains)
  if (copy.costs) parts.push(copy.costs)
  return `- ${parts.join(' · ')}`
}

function section(spec: RoadSpec): string {
  const card = spec.slots.course.card
  const kind = candidateIds.has(spec.id) ? 'matching candidate' : 'alternatives only'
  const lines = [
    `## ${spec.label}`,
    '',
    `- id: \`${spec.id}\` · ${writtenIds.has(spec.id) ? 'hand-written · ' : ''}${kind}`,
    `- city: ${cityById(spec.cityId).name} (alternative city: ${cityById(spec.altCityId).name}) · ${spec.level} · ${spec.stays ? `stays, ${spec.prRoute}` : 'goes home'}`,
    `- course: ${courseName(spec.courseId)} (\`${spec.courseId}\`)`,
    `- alternative: ${courseName(spec.altCourseId)} (\`${spec.altCourseId}\`)`,
    `- stack: ${courseName(spec.stackCourseId)} (\`${spec.stackCourseId}\`)`,
    '',
    '### PR steps',
    '',
    ...PR_STEPS.map((s) => stepLine(s, spec.slots[s])),
    '',
    '### Course card',
    '',
    `- sub: ${card.sub}`,
    `- gains: ${card.gains ?? '(none)'}`,
    `- costs: ${card.costs ?? '(none)'}`,
    `- guide: ${card.guide ?? '(none)'}`,
    '',
  ]
  return lines.join('\n')
}

const specs = ALL_PICKS.map((p) => composeRoad(p))
const matching = specs.filter((s) => candidateIds.has(s.id)).length

const out = [
  '# Road gallery',
  '',
  'Generated by `bun run roads:gallery`; do not edit by hand. Every pick in `ALL_PICKS`, composed by `composeRoad`, for a human read. No model call.',
  '',
  `${specs.length} roads: ${matching} matching candidates (\`ROAD_CANDIDATES\`), ${specs.length - matching} alternatives only (reachable as another road's alternative or stack, never chosen by matching).`,
  '',
  '## The six hand-written roads',
  '',
  ...ROAD_KEYS.map(
    (k) =>
      `- [${k.label}](#${anchor(k.label)}) — \`${k.id}\`${candidateIds.has(k.id) ? '' : ' (alternatives only)'}`,
  ),
  '',
  '---',
  '',
  // The hand-written six first, then the rest in ALL_PICKS order.
  ...[
    ...specs.filter((s) => writtenIds.has(s.id)),
    ...specs.filter((s) => !writtenIds.has(s.id)),
  ].map(section),
].join('\n')

/** GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens. */
function anchor(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N} -]/gu, '')
    .replace(/ /g, '-')
}

const file = join(import.meta.dir, '..', 'docs', 'student-ai-roads', 'road-gallery.md')
writeFileSync(file, `${out}\n`)
const ids = new Set(ALL_PICKS.map(pickId))
console.log(`${specs.length} roads (${ids.size} distinct ids) written to ${file}`)
